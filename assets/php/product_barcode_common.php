/**
 * ساخت بارکد داخلی از شناسه واقعی کالا در دیتابیس.
 *
 * مثال: product_id = 125  →  M20000000125
 */
function product_internal_barcode(int $productId): string
{
    return 'M' . (string) (20000000000 + $productId);
}

