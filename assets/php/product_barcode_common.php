/**
 * ساخت رشته ماژولی کامل Code 128 (مجموعه B) برای مقدار ورودی.
 *
 * تنها کاراکترهای ASCII 32..126 پشتیبانی می‌شوند (بارکدهای داخلی M... و
 * بارکدهای استاندارد کالا معمولاً در همین محدوده هستند).
 *
 * @throws InvalidArgumentException در صورت وجود کاراکتر غیرقابل‌رمزگذاری
 */
function product_barcode_code128_bits(string $value): string
{
    $patterns = product_barcode_code128_patterns();
    $start = $patterns[104]; // Start B

    $checksum = 104;
    $dataBits = '';
    $len = strlen($value);
    for ($i = 0; $i < $len; $i++) {
        $ord = ord($value[$i]);
        if ($ord < 32 || $ord > 126) {
            throw new InvalidArgumentException('Code 128 فقط کاراکترهای ASCII 32 تا 126 را پشتیبانی می‌کند.');
        }
        $symbolValue = $ord - 32;
        $dataBits .= $patterns[$symbolValue];
        $checksum += $symbolValue * ($i + 1);
    }

    $checkValue = $checksum % 103;

    return $start . $dataBits . $patterns[$checkValue] . $patterns[106];
}

/**
 * تولید گرافیک SVG سیاه‌وسفید بارکد Code 128 برای مقدار ذخیره‌شده.
 *
 * خروجی فقط خطوط بارکد است (بدون متن) تا چیدمان برچسب مطابق مشخصات باشد:
 *   «بارکد» ← «شناسه کالا» ← «مقدار بارکد»
 *
 * @param int $barHeightPx       ارتفاع ناحیه بارکد
 * @param int $moduleWidthPx     عرض هر ماژول
 * @param int $quietZoneModules  ناحیه ساکت در هر طرف (باید ≥ ۱۰ ماژول باشد)
 */
function product_barcode_code128_svg(string $value, int $barHeightPx = 60, int $moduleWidthPx = 2, int $quietZoneModules = 10): string
{
    $bits = product_barcode_code128_bits($value);
    $modules = strlen($bits);

    $totalWidth = ($quietZoneModules + $modules + $quietZoneModules) * $moduleWidthPx;
    $startX = $quietZoneModules * $moduleWidthPx;

    $shapes = '';
    $inBar = false;
    $barX = $startX;
    $barWidth = 0;
    $cursorX = $startX;

    for ($i = 0; $i < $modules; $i++) {
        if ($bits[$i] === '1') {
            if ($inBar) {
                $barWidth += $moduleWidthPx;
            } else {
                $inBar = true;
                $barX = $cursorX;
                $barWidth = $moduleWidthPx;
            }
        } else {
            if ($inBar) {
                $shapes .= '<rect x="' . $barX . '" y="0" width="' . $barWidth . '" height="' . $barHeightPx . '"/>';
                $inBar = false;
            }
        }
        $cursorX += $moduleWidthPx;
    }
    if ($inBar) {
        $shapes .= '<rect x="' . $barX . '" y="0" width="' . $barWidth . '" height="' . $barHeightPx . '"/>';
    }

    $label = htmlspecialchars($value, ENT_QUOTES, 'UTF-8');

    return '<svg xmlns="http://www.w3.org/2000/svg" width="' . $totalWidth . '" height="' . $barHeightPx . '" viewBox="0 0 ' . $totalWidth . ' ' . $barHeightPx . '" role="img" aria-label="' . $label . '">'
        . '<rect width="' . $totalWidth . '" height="' . $barHeightPx . '" fill="#ffffff"/>'
        . '<g fill="#000000">' . $shapes . '</g>'
        . '</svg>';
}
